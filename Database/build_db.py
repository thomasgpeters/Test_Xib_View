#!/usr/bin/env python3
"""
build_db.py - build the app's SQLite database, from local SQL or from an ALS model.

Local schema (default) - Database/schema.sql + Database/seed.sql:

    python3 Database/build_db.py                            # -> Database/contacts.sqlite
    python3 Database/build_db.py --out ~/Desktop/contacts.sqlite
    python3 Database/build_db.py --no-seed                  # tables only

From an API Logic Server model - a saved /metadata response, or a live server:

    python3 Database/build_db.py --als metadata.json --out ~/Desktop/northwind.sqlite
    python3 Database/build_db.py --als http://localhost:5656 --with-data
    python3 Database/build_db.py --als http://host:5656 --user admin --password p --with-data

  --als writes the generated tables to Database/schema.als.sql (review/diff it),
  then builds the database from it. --with-data (live server only) copies each
  resource's records through the ALS JSON:API (up to --limit per resource).

The database is built in a temporary file and moved into place, so a failed build
never leaves a half-written file. An existing --out file is kept as <name>.bak.
Uses only the Python standard library.
"""
import argparse, json, os, shutil, sqlite3, sys, tempfile, urllib.error, urllib.parse, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
LOGIN_PATHS = ('/api/auth/login', '/api/authentication-User/login')   # stock ALS first


# ---------------------------------------------------------------- ALS access
def http_json(url, token=None, body=None):
    headers = {'Accept': 'application/vnd.api+json, application/json'}
    data = None
    if body is not None:
        data = json.dumps(body).encode()
        headers['Content-Type'] = 'application/json'
    if token:
        headers['Authorization'] = f'Bearer {token}'
    req = urllib.request.Request(url, data=data, headers=headers, method='POST' if data else 'GET')
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode() or 'null')


def als_login(host, user, password):
    if not user:
        return None
    for path in LOGIN_PATHS:
        try:
            return http_json(host + path, body={'username': user, 'password': password or ''})['access_token']
        except urllib.error.HTTPError as e:
            if e.code == 404:
                continue                       # endpoint not present - try the next one
            sys.exit(f'Login failed at {path}: HTTP {e.code}')
    sys.exit('Login failed: no login endpoint found ' + ' or '.join(LOGIN_PATHS))


def load_model(source, user, password):
    """Return (resources dict, host or None, token or None)."""
    if source.startswith(('http://', 'https://')):
        host = source.rstrip('/')
        token = als_login(host, user, password)
        model = http_json(host + '/metadata?include=attributes', token)
        return model['resources'], host, token
    with open(os.path.expanduser(source)) as f:
        return json.load(f)['resources'], None, None


# ---------------------------------------------------------------- schema
def q(name):
    return '"' + name.replace('"', '""') + '"'


def schema_from_model(resources):
    """CREATE TABLE statements from ALS resources. Declared SQL types are kept as-is
    (SQLite accepts e.g. VARCHAR(40)). ALS /metadata?include=attributes carries no key
    information, so a primary key is declared only if an attribute says so."""
    out = ['-- Generated by build_db.py from an API Logic Server model. Do not edit;',
           '-- regenerate with:  python3 Database/build_db.py --als <metadata.json | server URL>', '']
    for name in sorted(resources):
        attrs = resources[name].get('attributes', [])
        if not attrs:
            continue
        cols, keys = [], []
        for a in attrs:
            cols.append(f'    {q(a["name"])} {a.get("type") or "TEXT"}')
            if a.get('primary_key') or a.get('is_pk') or a.get('pk'):
                keys.append(q(a['name']))
        if keys:
            cols.append(f'    PRIMARY KEY ({", ".join(keys)})')
        out.append(f'CREATE TABLE {q(name)} (\n' + ',\n'.join(cols) + '\n);\n')
    return '\n'.join(out)


def copy_als_data(db, resources, host, token, limit):
    for name in sorted(resources):
        cols = [a['name'] for a in resources[name].get('attributes', [])]
        if not cols:
            continue
        url = f'{host}/api/{urllib.parse.quote(name)}?page%5Blimit%5D={limit}&page%5Boffset%5D=0'
        try:
            rows = http_json(url, token).get('data', [])
        except urllib.error.HTTPError as e:
            print(f'  {name}: skipped (HTTP {e.code})'); continue
        sql = f'INSERT INTO {q(name)} ({", ".join(q(c) for c in cols)}) VALUES ({", ".join("?" * len(cols))})'
        db.executemany(sql, [[r.get('attributes', {}).get(c) for c in cols] for r in rows])
        print(f'  {name}: {len(rows)} rows')


# ---------------------------------------------------------------- build
def build(out_path, scripts, after=None):
    out_path = os.path.expanduser(out_path)
    fd, tmp = tempfile.mkstemp(suffix='.sqlite', dir=os.path.dirname(os.path.abspath(out_path)))
    os.close(fd)
    try:
        db = sqlite3.connect(tmp)
        for label, sql in scripts:
            try:
                db.executescript(sql)
            except sqlite3.Error as e:
                sys.exit(f'{label}: {e}')
        if after:
            after(db)
        db.commit()
        db.close()
        if os.path.exists(out_path):
            shutil.copy2(out_path, out_path + '.bak')
        os.replace(tmp, out_path)
        os.chmod(out_path, 0o644)
    finally:
        if os.path.exists(tmp):
            os.remove(tmp)
    db = sqlite3.connect(out_path)
    for (t,) in db.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"):
        print(f'  {t}: {db.execute(f"SELECT COUNT(*) FROM {q(t)}").fetchone()[0]} rows')
    db.close()
    print(f'Wrote {out_path}')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default=os.path.join(HERE, 'contacts.sqlite'), help='database file to write')
    ap.add_argument('--no-seed', action='store_true', help='tables only, no sample data (local mode)')
    ap.add_argument('--als', metavar='JSON_OR_URL', help='build from an ALS model instead of schema.sql')
    ap.add_argument('--user'); ap.add_argument('--password')
    ap.add_argument('--with-data', action='store_true', help='copy records from the ALS server')
    ap.add_argument('--limit', type=int, default=1000, help='max records per resource (--with-data)')
    a = ap.parse_args()

    if not a.als:
        scripts = [('schema.sql', open(os.path.join(HERE, 'schema.sql')).read())]
        if not a.no_seed:
            scripts.append(('seed.sql', open(os.path.join(HERE, 'seed.sql')).read()))
        build(a.out, scripts)
        return

    resources, host, token = load_model(a.als, a.user, a.password)
    schema = schema_from_model(resources)
    schema_path = os.path.join(HERE, 'schema.als.sql')
    with open(schema_path, 'w') as f:
        f.write(schema)
    print(f'Wrote {schema_path} ({len(resources)} resources)')
    if a.with_data and not host:
        sys.exit('--with-data needs a live ALS server URL, not a metadata file')
    after = (lambda db: copy_als_data(db, resources, host, token, a.limit)) if a.with_data else None
    build(a.out, [('schema.als.sql', schema)], after)


if __name__ == '__main__':
    main()
